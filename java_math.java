public class java_math {
    public static void main(String[] args) {
        // Math class examples
        double num1 = 5.7;
        double num2 = 3.2;

        // Absolute value
        System.out.println("Absolute value of -5: " + Math.abs(-5));

        // Power
        System.out.println("5 raised to the power of 3: " + Math.pow(num1, 3));

        // Square root
        System.out.println("Square root of 16: " + Math.sqrt(16));

        // Maximum and minimum
        System.out.println("Maximum of num1 and num2: " + Math.max(num1, num2));
        System.out.println("Minimum of num1 and num2: " + Math.min(num1, num2));

        // Rounding
        System.out.println("Rounded value of num1: " + Math.round(num1));
    }
}